#!/usr/bin/env python3
"""Export a saved scene artifact without training. Standard library only."""
import argparse
import json
import math
from pathlib import Path


def floats(values):
    result = []
    for value in values:
        s = format(float(value), '.9g')
        if '.' not in s and 'e' not in s.lower():
            s += '.0'
        result.append(s + 'f')
    return ', '.join(result)


def render(model):
    assert model['feature_count'] == 92
    assert model['classes'] == ['street', 'highway', 'market']
    arrays = [('kMu', model['normalization']['mean'], 92),
              ('kSigma', model['normalization']['std'], 92),
              ('kW', model['folded_weights'], 276),
              ('kB', model['folded_bias'], 3)]
    for _, values, size in arrays:
        assert len(values) == size and all(math.isfinite(x) for x in values)
    assert all(x > 0 for x in model['normalization']['std'])
    header = ['// Generated by experiments/scene-model/export_model.py. Do not edit by hand.',
              '// Experimental scene head; golden cases verify implementation, not generalization.',
              '#pragma once', '#include <cstddef>', 'namespace scene_model {',
              'constexpr const char* kVersion = ' + json.dumps(model['version']) + ';',
              'constexpr std::size_t kFeatureCount = 92;',
              'constexpr std::size_t kClassCount = 3;',
              'constexpr const char* kClassNames[kClassCount] = {"street", "highway", "market"};']
    for name, values, size in arrays:
        header += [f'constexpr float {name}[{size}] = {{', '    ' + floats(values) + ',', '};']
    header += ['inline void classify(const float* x, float* logits) {',
               '    for (std::size_t o = 0; o < kClassCount; ++o) {',
               '        float acc = kB[o];',
               '        for (std::size_t i = 0; i < kFeatureCount; ++i) acc += kW[o * kFeatureCount + i] * x[i];',
               '        logits[o] = acc;', '    }', '}', '}  // namespace scene_model']
    golden = ['// Generated by experiments/scene-model/export_model.py. Do not edit by hand.',
              '// Implementation equivalence only: these legacy cases participated in training.',
              '#pragma once', 'namespace scene_golden {',
              'struct Case { const char* label; float vector[92]; float logits[3]; int argmax; };',
              'constexpr Case kCases[] = {']
    for case in model['golden']:
        assert len(case['vector']) == 92 and len(case['logits']) == 3
        assert all(math.isfinite(x) for x in case['vector'] + case['logits'])
        assert case['label'] in model['classes'] and 0 <= case['argmax'] < 3
        golden.append('    {%s, {%s}, {%s}, %d},' %
                      (json.dumps(case['label']), floats(case['vector']),
                       floats(case['logits']), case['argmax']))
    golden += ['};', '}  // namespace scene_golden']
    return {'main/scene_model.h': '\n'.join(header) + '\n',
            'test/scene_golden.h': '\n'.join(golden) + '\n'}


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--model', type=Path, required=True)
    p.add_argument('--output-root', type=Path, required=True)
    p.add_argument('--check', action='store_true', help='compare only; never overwrite')
    args = p.parse_args()
    for name, content in render(json.loads(args.model.read_text())).items():
        dest = args.output_root / name
        if args.check:
            if not dest.exists() or dest.read_text() != content:
                raise SystemExit(f'Export mismatch: {name}')
        else:
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_text(content)
    print('scene export: headers match saved artifact' if args.check else 'scene export: wrote headers')


if __name__ == '__main__':
    main()
